import fs from "node:fs";

const artifactPath = "artifacts/contracts/RelayEscrow.sol/RelayEscrow.json";
const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
fs.mkdirSync("src/lib/contracts", { recursive: true });
const output = `/* Generated by scripts/export-abi.mjs from ${artifactPath}. Do not edit by hand. */\nexport const relayEscrowAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
fs.writeFileSync("src/lib/contracts/relayEscrowAbi.ts", output);
console.log(`Wrote src/lib/contracts/relayEscrowAbi.ts (${artifact.abi.length} entries)`);
